export default function LegalPage() {
  const { slug } = useParams<{ slug: string }>();
  const content = slug ? CONTENT[slug] : undefined;

  if (!content) {
    return (
      <div className="mx-auto max-w-(--breakpoint-md) px-4 py-24">
        <ErrorState
          title="ئەم پەڕەیە نەدۆزرایەوە"
          description="ئەم بەشە یاساییە بوونی نییە."
          action={
            <Link to="/" className={buttonClassName("primary", "md")}>
              گەڕانەوە بۆ سەرەکی
            </Link>
          }
        />
      </div>
    );
  }

  return (
    <div className="mx-auto max-w-(--breakpoint-md) px-4 py-12 sm:px-6 sm:py-16">
      <h1 className="text-3xl font-extrabold text-(--color-text-primary)">{content.title}</h1>
      <p className="mt-2 text-xs text-(--color-text-muted)">{content.updated}</p>
      <p className="mt-5 text-(--color-text-secondary)">{content.intro}</p>

      <div className="mt-8 flex flex-col gap-8">
        {content.sections.map((s) => (
          <section key={s.heading}>
            <h2 className="mb-3 text-lg font-bold text-(--color-text-primary)">{s.heading}</h2>
            <div className="flex flex-col gap-3">
              {s.body.map((p, i) => (
                <p key={i} className="leading-relaxed text-(--color-text-secondary)">
                  {p}
                </p>
              ))}
            </div>
          </section>
        ))}
      </div>
    </div>
  );
}
